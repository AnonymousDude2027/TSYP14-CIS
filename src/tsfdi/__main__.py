def build_parser() -> argparse.ArgumentParser:
    p = argparse.ArgumentParser(prog="tsfdi", description=__doc__,
                                formatter_class=argparse.RawDescriptionHelpFormatter)
    sub = p.add_subparsers(dest="command", required=True)

    s = sub.add_parser("fetch", help="build the offline data bundle (network)")
    s.add_argument("--sites", nargs="*", default=None)
    s.add_argument("--force", action="store_true")
    s.set_defaults(func=cmd_fetch)

    s = sub.add_parser("data-verify", help="verify the bundle against the signed manifest")
    s.set_defaults(func=cmd_data_verify)

    s = sub.add_parser("sites", help="re-measure site completeness")
    s.set_defaults(func=cmd_sites)

    s = sub.add_parser("gonogo", help="go/no-go experiment (spec section 6)")
    s.add_argument("--sites", nargs="*", default=None)
    s.add_argument("--no-mc", action="store_true", help="skip the Monte-Carlo minimum detectable bias")
    s.set_defaults(func=cmd_gonogo)

    s = sub.add_parser("calibrate", help="fit and calibrate all models")
    s.add_argument("--sites", nargs="*", default=None)
    s.add_argument("--budget", type=float, default=None)
    s.set_defaults(func=cmd_calibrate)

    s = sub.add_parser("stream", help="stream one series through L0-L5")
    s.add_argument("site")
    s.add_argument("variable", nargs="?", default="TMAX")
    s.add_argument("--attack", default="none",
                   choices=["none", "step", "ramp", "replay", "scaling", "noise_shaped",
                            "stuck_at", "dropout", "spike"])
    s.add_argument("--magnitude", type=float, default=3.0, help="bias in sigma units")
    s.add_argument("--percent", type=float, default=None, help="bias as %% of seasonal range")
    s.add_argument("--onset", type=int, default=None)
    s.add_argument("--length", type=int, default=7)
    s.add_argument("--max-alerts", type=int, default=3)
    s.set_defaults(func=cmd_stream)

    s = sub.add_parser("experiments", help="run the full evaluation")
    s.add_argument("--quick", action="store_true", help="reduced grid for a smoke test")
    s.add_argument("--sites", nargs="*", default=None)
    s.add_argument("--steps", default=None,
                   help="comma-separated subset: standard_profile,grid,false_alarms,"
                        "baselines,ablation,evasion,evasion_curve,diagnosis,efficiency")
    s.set_defaults(func=cmd_experiments)

    s = sub.add_parser("report-text", help="build docs/report.md from the generated results")
    s.set_defaults(func=cmd_report_text)

    s = sub.add_parser("report-static", help="write the self-contained HTML report (no Streamlit)")
    s.add_argument("--site", default="CARTHAGE")
    s.add_argument("--variable", default="TMAX")
    s.add_argument("--attack", default="step")
    s.add_argument("--magnitude", type=float, default=3.0)
    s.set_defaults(func=cmd_report_static)
    s = sub.add_parser("report-pdf", help="render docs/report.md and the appendix to PDF")
    s.set_defaults(func=cmd_report_pdf)
    s = sub.add_parser("report-figures", help="build tables and figures")
    s.set_defaults(func=cmd_report_figures)

    s = sub.add_parser("verify", help="compare against expected_results.json")
    s.add_argument("--tol", type=float, default=0.02)
    s.add_argument("--regenerate", action="store_true")
    s.set_defaults(func=cmd_verify)

    s = sub.add_parser("bench", help="provenance overhead benchmark")
    s.add_argument("--n", type=int, default=100_000)
    s.set_defaults(func=cmd_bench)

    s = sub.add_parser("selftest", help="run the numerical unit tests")
    s.set_defaults(func=cmd_selftest)
    return p


def main(argv: list[str] | None = None) -> int:
    args = build_parser().parse_args(argv)
    return int(args.func(args) or 0)


if __name__ == "__main__":  # pragma: no cover
    raise SystemExit(main())
