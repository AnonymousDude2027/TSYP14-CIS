"""Site selection and completeness measurement (specification section 5.3).

The specification's *default* criterion is "at least 8 of 10 years with at least
95 % completeness for TMAX, TMIN and PRCP".  Measured on the real GHCN-Daily
archive that criterion is unattainable for most of the climate classes we need:
TMAX coverage is systematically worse than TMIN in the West-African, Saharan and
Middle-Eastern networks, and many stations report temperature on a 60-70 % duty
cycle.  This script therefore

1. measures completeness per (station, variable) instead of assuming it,
2. ranks candidates within each climate box by the completeness of the variable
   actually used, and
3. writes the measured numbers to ``results/site_selection.csv`` so that every
   claim about a site's data quality in the report can be checked.

The deviation from the 95 % default is documented in docs/site_selection.md and
is not hidden: a station with 65 % coverage is used *because* the pipeline is
designed to work with gaps (no interpolation, effective-sample-size
normalisation, state-space gap handling in SP3), and its completeness is printed
in the site table.
"""
from __future__ import annotations

import numpy as np
import pandas as pd

from . import config
from .io import load_pair
from .sp.expectation import robust_scale


def measure(site_name: str, variable: str) -> dict:
    b = load_pair(site_name, variable)
    n = len(b.dates)
    cal = b.mask_between(*config.period("calibration"))
    test = b.mask_between(*config.period("test"))
    ok = b.sensor_ok & b.reference_ok
    years = pd.DatetimeIndex(b.dates).year
    per_year = {}
    for y in sorted(set(years)):
        m = (years == y)
        per_year[int(y)] = float(ok[m].mean())
    good_years = sum(1 for v in per_year.values() if v >= 0.95)
    both = ok & np.isfinite(b.sensor) & np.isfinite(b.reference)
    return {
        "site": site_name, "station_id": b.site_id, "variable": variable,
        "climate": b.meta.get("climate"),
        "n_days": n,
        "completeness_overall": float(ok.mean()),
        "completeness_calibration": float(ok[cal].mean()),
        "completeness_test": float(ok[test].mean()),
        "years_at_or_above_95pct": good_years,
        "lag_days": b.lag_days,
        "lag_correlation": float(b.meta.get("lag_corr", np.nan)),
        "n_paired": int(both.sum()),
    }


def select_sites(write: bool = True) -> pd.DataFrame:
    rows = []
    for s in config.sites():
        for v in s.variables:
            try:
                rows.append(measure(s.name, v))
            except Exception as exc:  # noqa: BLE001
                rows.append({"site": s.name, "station_id": s.id, "variable": v, "error": str(exc)})
    df = pd.DataFrame(rows)
    if write:
        df.to_csv(config.results_dir() / "site_selection.csv", index=False)
        _write_markdown(df)
    return df


def _write_markdown(df: pd.DataFrame) -> None:
    lines = ["# Site selection and data completeness", "",
             "Generated by `python -m tsfdi sites`.  Completeness is the fraction of days with a "
             "non-null, quality-flag-clean sensor value **and** a non-null reference value.", ""]
    sub = df.drop(columns=[c for c in ("error",) if c in df.columns]).copy()
    for c in sub.columns:
        if sub[c].dtype.kind == "f":
            sub[c] = sub[c].round(3)
    try:
        lines.append(sub.to_markdown(index=False))
    except ImportError:            # tabulate is optional; the markdown table is not
        cols = list(sub.columns)
        lines.append("| " + " | ".join(cols) + " |")
        lines.append("|" + "|".join("---" for _ in cols) + "|")
        for _, row in sub.iterrows():
            lines.append("| " + " | ".join(str(row[c]) for c in cols) + " |")
    lines.append("")
    lines += [
        "## Why the 95 % default is relaxed",
        "",
        "The specification's default asks for 8 of 10 years at >= 95 % completeness for TMAX, "
        "TMIN and PRCP.  On the GHCN-Daily archive this is met by the European, North-American "
        "and Nordic stations in the bundle but **not** by the Tunisian, Egyptian and Saharan "
        "stations, where TMAX is reported on a 60-75 % duty cycle (TMIN is denser).  Two "
        "options existed: drop the North-African sites, or design for gaps.  The second was "
        "chosen because a false-data-injection system that only works on complete records is "
        "useless in exactly the regions where the challenge is motivated.",
        "",
        "Design consequences, all of them exercised by the code:",
        "",
        "* no interpolation anywhere in the detection path (SP1 flags gaps; every statistic is "
        "normalised by the effective sample size of its window);",
        "* SP3's AR filter treats a missing day as a missing observation of a state-space model "
        "instead of discarding the p days that follow it (otherwise an AR(5) filter would keep "
        "7 % of CARTHAGE's samples);",
        "* the false-alarm calibration resamples the *actual* gap pattern, so periods with "
        "different data density do not silently change the alarm rate.",
    ]
    (config.results_dir() / "site_selection.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
